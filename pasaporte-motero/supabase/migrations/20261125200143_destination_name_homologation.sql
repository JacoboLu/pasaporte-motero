create or replace function public.normalize_destination_name(input text)
returns text language sql immutable parallel safe
as $$
  select trim(both '-' from regexp_replace(
    translate(lower(coalesce(input,'')), 'áéíóúüñ', 'aeiouun'),
    '[^a-z0-9]+', '-', 'g'
  ));
$$;

create table if not exists public.destination_name_aliases (
  id bigint generated by default as identity primary key,
  alias_name text not null,
  normalized_alias text generated always as (public.normalize_destination_name(alias_name)) stored,
  destination_id integer not null references public.destination_catalog(id) on delete restrict,
  source_note text,
  created_at timestamptz not null default now(),
  constraint destination_name_aliases_nonempty check (length(normalized_alias) > 0)
);
create unique index if not exists destination_name_aliases_normalized_uidx on public.destination_name_aliases(normalized_alias);
create index if not exists destination_name_aliases_destination_idx on public.destination_name_aliases(destination_id);

